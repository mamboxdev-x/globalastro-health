-- GlobalAstro Health — base du poste sol (Supabase / PostgreSQL)
--
-- À coller dans Supabase : SQL Editor → New query → Run.
-- Le bord n'utilise pas cette base : à bord, les mesures restent locales (module central,
-- mesures.csv) et repartent vers le sol à la fenêtre de communication suivante.
--
-- Prototype : l'accès se fait avec la clé publique du projet, sans authentification Supabase.
-- Les politiques ci-dessous ouvrent donc les trois tables à la clé anonyme. À ne pas réutiliser
-- tel quel pour des données réelles.

create table if not exists comptes (
  id           bigint generated by default as identity primary key,
  identifiant  text not null unique,
  role         text not null check (role in ('astro', 'sol')),
  empreinte    text not null,                    -- SHA-256, jamais le mot de passe en clair
  profil       jsonb not null default '{}'::jsonb,
  cree_le      timestamptz not null default now()
);

create table if not exists consignes (
  id            bigint generated by default as identity primary key,
  destinataire  text not null,
  texte         text not null,
  mise_en_file  text not null default '',
  etat          text not null default 'attente' check (etat in ('attente', 'transmise', 'lue')),
  cree_le       timestamptz not null default now(),
  lue_le        timestamptz
);

-- Ce que le poste sol reçoit du bord : mesures, alertes, état de l'équipage.
create table if not exists mesures (
  id          bigint generated by default as identity primary key,
  date_utc    timestamptz not null default now(),
  membre      text not null default 'cdr.mbaye',
  capteur     text not null default '',
  parametre   text not null,
  valeur      text not null default '',
  unite       text not null default '',
  statut      text not null default 'info',
  recu_le     timestamptz not null default now()
);

create index if not exists mesures_parametre_idx on mesures (parametre, date_utc desc);
create index if not exists consignes_destinataire_idx on consignes (destinataire, cree_le desc);

alter table comptes  enable row level security;
alter table consignes enable row level security;
alter table mesures  enable row level security;

drop policy if exists prototype_comptes on comptes;
drop policy if exists prototype_consignes on consignes;
drop policy if exists prototype_mesures on mesures;

create policy prototype_comptes on comptes
  for all to anon using (true) with check (true);

create policy prototype_consignes on consignes
  for all to anon using (true) with check (true);

create policy prototype_mesures on mesures
  for all to anon using (true) with check (true);

-- Vérification : ces trois requêtes doivent renvoyer 0 ligne, sans erreur.
select count(*) as comptes   from comptes;
select count(*) as consignes from consignes;
select count(*) as mesures   from mesures;
